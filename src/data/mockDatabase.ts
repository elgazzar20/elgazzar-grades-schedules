type AssessmentTemplate = 'primary' | 'prep' | 'secondary';

interface SeedStudentInput {
  id: string;
  name: string;
  group: string;
  q1: number; // out of 10
  q2: number; // out of 10
  exam: number; // out of 50
  hw: number; // out of 10
  attendance: string;
  note: string;
}

function buildStudentRecord(
  grade: string,
  template: AssessmentTemplate,
  seed: SeedStudentInput
): StudentRecord {
  let titles: [string, string, string, string, string];

  if (template === 'primary') {
    titles = [
      'كويز الحساب والكسور (10)',
      'كويز الهندسة والقياس (10)',
      'امتحان الشهر (50)',
      'الواجب والمواظبة (10)',
      'نسبة الحضور',
    ];
  } else if (template === 'prep') {
    titles = [
      'كويز الجبر (10)',
      'كويز الهندسة (10)',
      'امتحان الشهر (50)',
      'الواجب والمواظبة (10)',
      'نسبة الحضور',
    ];
  } else {
    titles = [
      'كويز الجبر والتفاضل (10)',
      'كويز المثلثات والهندسة (10)',
      'امتحان الشهر الشامل (50)',
      'الواجب والمواظبة (10)',
      'نسبة الحضور',
    ];
  }

  return {
    id: seed.id,
    name: seed.name,
    grade,
    group: seed.group,
    note: seed.note,
    scores: [
      { title: titles[0], value: `${seed.q1}/10` },
      { title: titles[1], value: `${seed.q2}/10` },
      { title: titles[2], value: `${seed.exam}/50` },
      { title: titles[3], value: `${seed.hw}/10` },
      { title: titles[4], value: seed.attendance },
    ],
  };
}

